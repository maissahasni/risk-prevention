export function parseCSV(csvText) {
    const lines = csvText.trim().split('\n');
    const headers = lines[0].split(',');

    return lines.slice(1).map(line => {
        const values = line.split(',');
        const entry = {};
        headers.forEach((header, index) => {
            const value = values[index];
            // Convert numeric values
            if (!isNaN(value) && value !== '') {
                entry[header] = parseFloat(value);
            } else {
                entry[header] = value;
            }
        });
        return entry;
    });
}

export const getDashboardData = () => {
    const data = parseCSV(RAW_CSV_DATA);
    // Add formatted time for charts
    return data.map(item => ({
        ...item,
        time: new Date(item.timestamp).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' })
    }));
};

export const getMachinesList = (data) => {
    const machines = {};
    data.forEach(item => {
        if (!machines[item.machine_id]) {
            machines[item.machine_id] = {
                id: item.machine_id,
                name: item.machine_name,
                type: item.machine_type,
                latestData: item
            };
        } else {
            // Keep updating to get the latest entry (assuming sorted by time)
            machines[item.machine_id].latestData = item;
        }
    });
    return Object.values(machines);
};

export const getMachineData = (data, machineId) => {
    return data.filter(item => item.machine_id === machineId);
};
